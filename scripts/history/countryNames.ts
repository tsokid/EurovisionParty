/** ISO code for a country name as written on Wikipedia; throws on unknown names. */
export function toIso(name: string): string {
  const key = name.replace(/\s+/g, ' ').trim().toLowerCase();
  const iso = NAMES[key];
  if (!iso) throw new Error(`toIso: unknown country name "${name}"`);
  return iso;
}
