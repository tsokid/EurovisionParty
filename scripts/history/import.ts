// Wikipedia history import (sub-project 2b).
//
//   tsx scripts/history/import.ts [--from 1956] [--to 2025]
//   tsx scripts/history/import.ts --from 2026 --to 2026 --snapshot-only
//
// For each year: fetch "Eurovision_Song_Contest_{year}" (cached under
// .cache/wikipedia/), parse it, write data/history/{year}.json. Then
// regenerate supabase/migrations/073_history_import.sql from every
// data/history/*.json up to 2025 (2026 is never touched).
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { fetchContestWikitext } from './fetchWikitext';
import { parseContest, type ContestRecord, type EntryRecord } from './parseContest';

const here = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(here, '../..');
export const DATA_DIR = path.join(ROOT, 'data/history');
const MIGRATION = path.join(ROOT, 'supabase/migrations/073_history_import.sql');
const LAST_YEAR = 2025;
const SLUG_RE = /^[a-z]+(-[a-z]+)*$/;
/** Fixed archived_at for every imported contest, so 073 is deterministic. */
const ARCHIVED_AT = '2026-10-31T00:00:00Z';

/** Lowercase ASCII slug with hyphens (Malmö → malmo, Tel Aviv → tel-aviv). */
export function slugify(name: string): string {
  const slug = name
    .replace(/[Ææ]/g, 'ae')
    .replace(/[Øø]/g, 'o')
    .replace(/ß/g, 'ss')
    .replace(/[Đđ]/g, 'd')
    .replace(/[Łł]/g, 'l')
    .replace(/ı/g, 'i')
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z]+/g, '-')
    .replace(/^-+|-+$/g, '');
  if (!SLUG_RE.test(slug)) throw new Error(`slugify: "${name}" gives invalid slug "${slug}"`);
  return slug;
}

/** JSON with object keys sorted at every level, 2-space indent, trailing newline. */
export function stableJson(value: unknown): string {
  const sort = (v: unknown): unknown => {
    if (Array.isArray(v)) return v.map(sort);
    if (v && typeof v === 'object') {
      return Object.fromEntries(
        Object.keys(v as Record<string, unknown>)
          .sort()
          .map((k) => [k, sort((v as Record<string, unknown>)[k])]),
      );
    }
    return v;
  };
  return JSON.stringify(sort(value), null, 2) + '\n';
}

function sqlValue(v: string | number | boolean | null): string {
  if (v === null) return 'null';
  if (typeof v === 'number') {
    if (!Number.isInteger(v)) throw new Error(`sqlValue: non-integer ${v}`);
    return String(v);
  }
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  return `'${v.replace(/'/g, "''")}'`;
}

/** Reads every data/history/{year}.json with year ≤ 2025, sorted by year. */
export function loadRecords(): ContestRecord[] {
  return readdirSync(DATA_DIR)
    .filter((f) => /^\d{4}\.json$/.test(f))
    .map((f) => JSON.parse(readFileSync(path.join(DATA_DIR, f), 'utf8')) as ContestRecord)
    .filter((r) => r.year <= LAST_YEAR)
    .sort((a, b) => a.year - b.year);
}

/** The full text of migration 073 for `records`. Deterministic. */
export function buildMigration(records: ContestRecord[]): string {
  const contests = records.map(
    (r) =>
      `  (${[
        r.year,
        sqlValue(r.host_iso),
        sqlValue(r.city),
        sqlValue(slugify(r.city)),
        sqlValue(r.semi1_date),
        sqlValue(r.semi2_date),
        sqlValue(r.final_date),
        `'archived'`,
        'false',
        sqlValue(r.cancelled),
        `'${ARCHIVED_AT}'`,
      ].join(', ')})`,
  );
  const entryCols: (keyof EntryRecord)[] = [
    'iso', 'artist', 'song', 'semi', 'semi_place', 'semi_points', 'qualified', 'in_final',
    'final_running_order', 'final_place', 'total_points', 'jury_points', 'televote_points',
  ];
  const entries = records.flatMap((r) =>
    [...r.entries]
      .sort((a, b) => a.iso.localeCompare(b.iso))
      .map((e) => `  (${[String(r.year), ...entryCols.map((c) => sqlValue(e[c])), `'import:wikipedia'`].join(', ')})`),
  );
  const years = records.map((r) => r.year);
  return `-- ============================================================
-- 073: Historical contests ${Math.min(...years)}-${Math.max(...years)} (sub-project 2b, spec §10)
-- ------------------------------------------------------------
-- GENERATED by scripts/history/import.ts from data/history/*.json.
-- Do not edit by hand; re-run the import instead.
--
-- Source: English Wikipedia, "Eurovision Song Contest {year}" articles,
-- CC BY-SA 4.0 (see content/SOURCES.md).
--
-- * contests: one row per year, stage 'archived', indexable false,
--   archived_at fixed at ${ARCHIVED_AT}. 2020 has cancelled = true
--   (planned dates kept) and its selected entries, with no results.
-- * contest_entries: source 'import:wikipedia'.
-- * Never touches 2026. Both inserts are "on conflict do nothing": an
--   existing contest row or entry is kept as is, and re-running this
--   migration is a no-op. Entries are inserted per (year, iso) even when
--   that year's contest row already existed; harmless at cutover, where
--   only 2026 exists.
-- ============================================================

begin;

insert into public.contests
  (year, host_iso, city, city_slug, semi1_date, semi2_date, final_date, stage, indexable, cancelled, archived_at)
values
${contests.join(',\n')}
on conflict (year) do nothing;

insert into public.contest_entries
  (year, ${entryCols.join(', ')}, source)
values
${entries.join(',\n')}
on conflict (year, iso) do nothing;

commit;
`;
}

function arg(name: string, fallback: number): number {
  const i = process.argv.indexOf(`--${name}`);
  if (i < 0) return fallback;
  const v = Number(process.argv[i + 1]);
  if (!Number.isInteger(v)) throw new Error(`--${name} needs a year`);
  return v;
}

/** The newest year --snapshot-only may import (data/history only, never 073). */
const SNAPSHOT_LAST_YEAR = 2026;

async function main(): Promise<void> {
  // --snapshot-only: write data/history/{year}.json for the local content
  // snapshot (scripts/snapshot/build-local.ts) and leave 073 alone. Only
  // then may --to go past LAST_YEAR: production gets 2026 from its own DB.
  const snapshotOnly = process.argv.includes('--snapshot-only');
  const from = arg('from', 1956);
  const to = arg('to', LAST_YEAR);
  const maxTo = snapshotOnly ? SNAPSHOT_LAST_YEAR : LAST_YEAR;
  if (to > maxTo) {
    throw new Error(
      snapshotOnly
        ? `--to may not exceed ${SNAPSHOT_LAST_YEAR}`
        : `--to may not exceed ${LAST_YEAR} (2026 is live data); use --snapshot-only for data/history only`,
    );
  }
  mkdirSync(DATA_DIR, { recursive: true });
  for (let year = from; year <= to; year++) {
    const record = parseContest(year, await fetchContestWikitext(year));
    writeFileSync(path.join(DATA_DIR, `${year}.json`), stableJson(record), 'utf8');
    const finals = record.entries.filter((e) => e.in_final).length;
    const semis = record.entries.filter((e) => e.semi !== null).length;
    console.log(`${year}: ${record.entries.length} entries (${finals} final, ${semis} semi) ${record.city}, ${record.host_iso}`);
  }
  if (snapshotOnly) return console.log('--snapshot-only: 073 not regenerated');
  writeFileSync(MIGRATION, buildMigration(loadRecords()), 'utf8');
  console.log(`wrote ${path.relative(ROOT, MIGRATION)}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
