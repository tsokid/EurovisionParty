// Generates supabase/migrations/075_backfill_2026_semis.sql (final-review C1).
//
//   tsx scripts/history/backfill2026Semis.ts
//
// Production 2026 came from the old grand-final tables (070), so it has no
// semi-final data. 075 sets semi, semi_place, semi_points and qualified for
// every 2026 entry that ran in a semi-final, from data/history/2026.json.
// Deterministic: entries sorted by ISO, no timestamps in the text.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { DATA_DIR, sqlValue } from './import';
import type { ContestRecord } from './parseContest';

const here = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(here, '../..');
const MIGRATION = path.join(ROOT, 'supabase/migrations/075_backfill_2026_semis.sql');

/** The full text of migration 075. */
export function build075(): string {
  const record = JSON.parse(readFileSync(path.join(DATA_DIR, '2026.json'), 'utf8')) as ContestRecord;
  const rows = record.entries
    .filter((e) => e.semi !== null)
    .sort((a, b) => (a.iso < b.iso ? -1 : a.iso > b.iso ? 1 : 0));
  const values = rows.map(
    (e) => `    (${[sqlValue(e.iso), sqlValue(e.semi), sqlValue(e.semi_place), sqlValue(e.semi_points), sqlValue(e.qualified)].join(', ')})`,
  );
  return `-- ============================================================
-- 075: Backfill 2026 semi-final data (final review C1)
-- ------------------------------------------------------------
-- GENERATED by scripts/history/backfill2026Semis.ts from
-- data/history/2026.json. Do not edit by hand; re-run the script.
--
-- 070 copied 2026 from the old grand-final tables, which hold no
-- semi-final data. Without this, the first Publish would state that no
-- country ran in a semi-final. Sets semi, semi_place, semi_points and
-- qualified for the ${rows.length} entries that ran in a semi-final. Never
-- touches in_final, final places or points (072's guard data).
--
-- Plain SQL, not a parser write (app.writer unset), so the B9 guard on
-- finalized years does not apply. Idempotent: only rows that differ are
-- updated, so a re-run changes nothing (updated_at included). Raises
-- unless exactly ${rows.length} 2026 entries end up with a semi.
-- ============================================================

begin;

update public.contest_entries e
   set semi        = v.semi,
       semi_place  = v.semi_place,
       semi_points = v.semi_points,
       qualified   = v.qualified,
       updated_at  = now()
  from (values
${values.join(',\n')}
  ) as v(iso, semi, semi_place, semi_points, qualified)
 where e.year = 2026
   and e.iso = v.iso
   and (e.semi, e.semi_place, e.semi_points, e.qualified)
       is distinct from (v.semi::smallint, v.semi_place::smallint, v.semi_points::int, v.qualified::boolean);

do $$
declare
  v_count int;
begin
  select count(*) into v_count from public.contest_entries where year = 2026 and semi is not null;
  if v_count <> ${rows.length} then
    raise exception '2026 entries with a semi: %; expected ${rows.length}. 075 aborted.', v_count;
  end if;
end $$;

commit;
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(MIGRATION, build075(), 'utf8');
  console.log(`wrote ${path.relative(ROOT, MIGRATION)}`);
}
