-- ── 2. Retroactively recompute is_correct + points_awarded ───────────────────
-- The corrected CTE captures old_points BEFORE the UPDATE so the delta is exact.
WITH corrected AS (
  SELECT
    qa.id                                                             AS answer_id,
    qa.player_id,
    COALESCE(qa.points_awarded, 0)                                   AS old_points,
    (qa.answer_index IS NOT NULL AND qa.answer_index = qq.correct_index)
                                                                      AS new_is_correct,
    CASE
      WHEN qa.answer_index IS NOT NULL AND qa.answer_index = qq.correct_index THEN
        CASE
          WHEN COALESCE(qa.response_seconds, 16) <= 3  THEN 12
          WHEN COALESCE(qa.response_seconds, 16) <= 7  THEN 8
          ELSE 4
        END
      ELSE 0
    END                                                               AS new_points
  FROM quiz_answers qa
  JOIN quiz_questions qq ON qq.id = qa.question_id
),
updated AS (
  UPDATE quiz_answers qa
  SET
    is_correct     = c.new_is_correct,
    points_awarded = c.new_points
  FROM corrected c
  WHERE qa.id = c.answer_id
    AND (
      qa.is_correct != c.new_is_correct
      OR COALESCE(qa.points_awarded, 0) != c.new_points
    )
  RETURNING c.player_id, (c.new_points - c.old_points) AS delta
)
-- ── 3. Reconcile player quiz_points totals ───────────────────────────────────
UPDATE players p
SET quiz_points = GREATEST(0, quiz_points + agg.total_delta)
FROM (
  SELECT player_id, SUM(delta) AS total_delta
  FROM updated
  GROUP BY player_id
) agg
WHERE p.id = agg.player_id;
